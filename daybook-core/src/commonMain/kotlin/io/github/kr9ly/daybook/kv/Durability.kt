package io.github.kr9ly.daybook.kv

/**
 * 書き込みの耐久性ポリシー。[Daybook.open] のオプションとして指定する。
 *
 * どちらのモードでもディスク上のアトミック性（クラッシュ時に部分適用された
 * バッチが残らないこと）は変わらない。違いは「いつまでの書き込みが残るか」だけ。
 */
public enum class Durability {

    /** 書き込みごとに fsync する。遅いが電源断まで耐える。 */
    SYNC,

    /** OS のページキャッシュに任せる。プロセスクラッシュには耐える（既定）。 */
    ASYNC,
}
